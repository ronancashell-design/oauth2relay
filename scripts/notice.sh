# Writes NOTICE to stdout: the copyright and trademark notice, the licence of
# every third-party package compiled into the release binaries, and the
# NOTICE files of those packages. Run it with "make notice"; "make licenses"
# fails if NOTICE is out of date.
#
# GO_LICENSES is the go-licenses binary (the Makefile installs it in .tools).
set -euo pipefail
export LC_ALL=C

GO_LICENSES=${GO_LICENSES:-go-licenses}
# The dependencies differ by platform, so cover every release platform.
PLATFORMS=${PLATFORMS:-"linux darwin windows"}

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

for os in $PLATFORMS; do
	if ! GOOS=$os "$GO_LICENSES" report ./... >>"$tmp/report.csv" 2>"$tmp/err"; then
		cat "$tmp/err" >&2
		exit 1
	fi
	if ! GOOS=$os "$GO_LICENSES" save ./... --save_path="$tmp/save-$os" 2>"$tmp/err"; then
		cat "$tmp/err" >&2
		exit 1
	fi
done
# Lines are "package,licence URL,licence"; drop this module.
MODULE=$(go list -m)
grep -v "^$MODULE[,/]" "$tmp/report.csv" | sort -u >"$tmp/deps.csv"

cat <<'EOF'
OAUTH2Relay
Copyright 2024-2026 Fijomi Systems SL

This product is licensed under the Apache License, Version 2.0 (see the
LICENSE file).

"OAUTH2Relay" and the OAUTH2Relay logos are trademarks of Fijomi Systems SL.
The Apache License does not grant permission to use them, except as needed
to describe the origin of the software (Section 6 of the License).

Commercial features and support are available from Fijomi Systems SL under
a separate commercial license. They are not part of this repository.

--------------------------------------------------------------------------
Third-party software
--------------------------------------------------------------------------

This section is generated by scripts/notice.sh; do not edit it by hand.

The binary distribution of this product includes the following third-party
packages, each under its own license. The full license texts are in each
package's source distribution.
EOF

licence_name() {
	case $1 in
	Apache-2.0) echo "Apache License 2.0" ;;
	MIT) echo "MIT License" ;;
	BSD-2-Clause) echo "BSD 2-Clause License" ;;
	BSD-3-Clause) echo "BSD 3-Clause License" ;;
	MPL-2.0) echo "Mozilla Public License 2.0" ;;
	*) echo "$1" ;;
	esac
}

for licence in $(cut -d, -f3 "$tmp/deps.csv" | sort -u); do
	echo
	licence_name "$licence"
	[ "$licence" = BSD-3-Clause ] && echo "  The Go standard library"
	awk -F, -v l="$licence" '$3 == l { print "  " $1 }' "$tmp/deps.csv"
	if [ "$licence" = MPL-2.0 ]; then
		echo "  These packages are used unmodified. Their source code is available"
		echo "  at the package paths above."
	fi
done

echo
echo "The following notices are reproduced as required by the Apache License 2.0:"
# save copies each package's NOTICE file to <save_path>/<package>/.
(cd "$tmp" && find save-* -iname 'NOTICE*' -type f | sed 's|^save-[^/]*/||' | sort -u) |
	while read -r path; do
		pkg=${path%/*}
		case $pkg in "$MODULE" | "$MODULE"/*) continue ;; esac
		file=$(ls "$tmp"/save-*/"$path" | head -1)
		echo
		echo "  --- $pkg ---"
		sed -e 's/[[:space:]]*$//' -e 's/^./  &/' "$file"
	done
